#!/usr/bin/env node
/**
 * Generates thin standalone Angular wrappers + routes for advanced PDF tools.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { PDF_ADVANCED_TOOLS } from './pdf-advanced-tools.registry.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '../..');
const componentRoot = path.join(root, 'libs/pdf-tools/src/lib/component');
const routesFile = path.join(root, 'apps/tools-site/src/app/routes/pdf-tools.routes.ts');
const indexFile = path.join(root, 'libs/pdf-tools/src/index.ts');
const typesOut = path.join(root, 'libs/pdf-tools/src/lib/advanced/pdf-advanced-tools.registry.ts');

function toPascal(kebab) {
  return kebab
    .split('-')
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join('');
}

function escapeTs(str) {
  return str.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

// Emit TypeScript registry for the Angular app
const tsRegistry = `/* AUTO-GENERATED by scripts/pdf-tools/generate-advanced-pdf-tools.mjs — do not edit by hand */
export type PdfAdvancedInputKind = 'pdf' | 'office' | 'multi-pdf' | 'text' | 'url' | 'markdown' | 'images' | 'none';
export type PdfAdvancedOutputKind = 'pdf' | 'text' | 'json' | 'zip' | 'epub' | 'csv' | 'html' | 'markdown' | 'docx' | 'xfdf';
export type PdfAdvancedCapability = 'solid' | 'heuristic' | 'requires-engine';

export interface PdfAdvancedConfigField {
  key: string;
  label: string;
  type: 'text' | 'number' | 'textarea' | 'select' | 'checkbox' | 'password';
  placeholder?: string;
  options?: string[];
  defaultValue?: string | number | boolean;
}

export interface PdfAdvancedToolDef {
  id: string;
  title: string;
  description: string;
  category: string;
  input: PdfAdvancedInputKind;
  output: PdfAdvancedOutputKind;
  endpoint: string;
  accept?: string;
  needsPassword?: boolean;
  needsCertificate?: boolean;
  configFields?: PdfAdvancedConfigField[];
  clientOnly?: boolean;
  /** When true, POST returns a job id; poll GET /jobs/{id} then download. */
  asyncJob?: boolean;
  capability?: PdfAdvancedCapability;
  honestyNote?: string;
}

export const PDF_ADVANCED_TOOLS: PdfAdvancedToolDef[] = ${JSON.stringify(PDF_ADVANCED_TOOLS, null, 2)};

export function getPdfAdvancedTool(id: string): PdfAdvancedToolDef | undefined {
  return PDF_ADVANCED_TOOLS.find((t) => t.id === id);
}
`;
fs.writeFileSync(typesOut, tsRegistry);

const routeEntries = [];
const exportLines = [];

/** Custom workbenches — keep routes/exports, do not overwrite component sources. */
const CUSTOM_COMPONENT_IDS = new Set(['pdf-redact']);

for (const tool of PDF_ADVANCED_TOOLS) {
  const dir = path.join(componentRoot, tool.id);
  fs.mkdirSync(dir, { recursive: true });
  const className = `${toPascal(tool.id)}Component`;
  const selector = `lib-${tool.id}`;
  if (!CUSTOM_COMPONENT_IDS.has(tool.id)) {
    const ts = `import { ChangeDetectionStrategy, Component } from '@angular/core';
import { PdfAdvancedWorkbenchComponent } from '../pdf-advanced-workbench/pdf-advanced-workbench';

@Component({
  selector: '${selector}',
  standalone: true,
  template: \`
    <lib-pdf-advanced-workbench toolId="${tool.id}" />
  \`,
  imports: [PdfAdvancedWorkbenchComponent],
  changeDetection: ChangeDetectionStrategy.OnPush,
})
export class ${className} {}
`;
    fs.writeFileSync(path.join(dir, `${tool.id}.ts`), ts);

    const spec = `import { ComponentFixture, TestBed } from '@angular/core/testing';
import { pdfToolTestProviders } from '../../shared/pdf-tool-test.utils';
import { ${className} } from './${tool.id}';

describe('${className}', () => {
  let fixture: ComponentFixture<${className}>;

  beforeEach(async () => {
    await TestBed.configureTestingModule({
      imports: [${className}],
      providers: pdfToolTestProviders(),
    }).compileComponents();

    fixture = TestBed.createComponent(${className});
    fixture.detectChanges();
  });

  it('should create the tool workbench wrapper', () => {
    expect(fixture.componentInstance).toBeTruthy();
  });
});
`;
    fs.writeFileSync(path.join(dir, `${tool.id}.spec.ts`), spec);
  }

  routeEntries.push(`  {
    path: '${tool.id}',
    loadComponent: () =>
      import('@tools-workspace/pdf-tools/${tool.id}/${tool.id}').then(m => m.${className}),
  },`);
  exportLines.push(`export * from './lib/component/${tool.id}/${tool.id}';`);
}

// Rebuild routes: keep hand-written base through qr-code-to-pdf, then one AUTO block.
let routes = fs.readFileSync(routesFile, 'utf8');
const baseMatch = routes.match(
  /^([\s\S]*?\n  \{\n    path: 'qr-code-to-pdf',\n    loadComponent: \(\) =>\n      import\('@tools-workspace\/pdf-tools\/qr-code-to-pdf\/qr-code-to-pdf'\)\.then\(m => m\.QrCodeToPdfComponent\),\n  \},)/
);
if (!baseMatch) {
  throw new Error(
    'Could not find hand-written PDF_TOOLS_ROUTES base ending at qr-code-to-pdf. Fix pdf-tools.routes.ts manually.'
  );
}
routes =
  baseMatch[1] +
  `\n\n  // —— AUTO: advanced PDF tools (generated) ——\n` +
  routeEntries.join('\n') +
  `\n];\n`;
fs.writeFileSync(routesFile, routes);

// Patch index exports
let index = fs.readFileSync(indexFile, 'utf8');
index = index.replace(/\n\/\/ —— AUTO: advanced PDF tools[\s\S]*$/, '');
index += `\n// —— AUTO: advanced PDF tools (generated) ——\n`;
index += `export * from './lib/advanced/pdf-advanced-tools.registry';\n`;
index += `export * from './lib/component/pdf-advanced-workbench/pdf-advanced-workbench';\n`;
index += exportLines.join('\n') + '\n';
fs.writeFileSync(indexFile, index);

console.log(`Generated ${PDF_ADVANCED_TOOLS.length} advanced PDF tools.`);
